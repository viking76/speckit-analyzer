#!/usr/bin/env bash
# speckit-analyze integration script
# This script installs the /speckit.analyze command into an existing speckit setup
# Usage: ./integrate-analyze.sh [--repo-root PATH] [--force]

set -euo pipefail

SCRIPT_DIR="$(CDPATH="" cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT=""
FORCE=false

# Parse arguments
while [[ $# -gt 0 ]]; do
    case $1 in
        --repo-root)
            REPO_ROOT="$2"
            shift 2
            ;;
        --force)
            FORCE=true
            shift
            ;;
        --help|-h)
            echo "Usage: $0 [--repo-root PATH] [--force]"
            echo ""
            echo "Integrates speckit-analyze extension into an existing speckit setup."
            echo ""
            echo "Options:"
            echo "  --repo-root PATH   Specify repository root (default: auto-detect)"
            echo "  --force            Overwrite existing files without prompting"
            echo "  --help, -h         Show this help message"
            exit 0
            ;;
        *)
            echo "Unknown option: $1" >&2
            exit 1
            ;;
    esac
done

# Auto-detect repo root if not provided
if [[ -z "$REPO_ROOT" ]]; then
    if git rev-parse --show-toplevel >/dev/null 2>&1; then
        REPO_ROOT=$(git rev-parse --show-toplevel)
    else
        # Try to find .specify directory
        dir="$SCRIPT_DIR"
        while [[ "$dir" != "/" ]]; do
            if [[ -d "$dir/.specify" ]]; then
                REPO_ROOT="$dir"
                break
            fi
            dir="$(dirname "$dir")"
        done
    fi
fi

if [[ -z "$REPO_ROOT" ]] || [[ ! -d "$REPO_ROOT/.specify" ]]; then
    echo "Error: Could not find speckit repository root. Please specify with --repo-root." >&2
    exit 1
fi

SPECIFY_DIR="$REPO_ROOT/.specify"
SCRIPTS_DIR="$SPECIFY_DIR/scripts/bash"
TEMPLATES_DIR="$SPECIFY_DIR/templates"
PYTHON_DIR="$SPECIFY_DIR/python/speckit_analyzer"

# 1. Verify analyzer package exists
if [[ ! -d "$PYTHON_DIR" ]]; then
    echo "Error: speckit_analyzer package not found at $PYTHON_DIR" >&2
    echo "Please ensure the analyzer package is installed first." >&2
    exit 1
fi

# 2. Install analyze-tasks.sh wrapper (already exists)
ANALYZE_WRAPPER="$SCRIPTS_DIR/analyze-tasks.sh"
if [[ ! -f "$ANALYZE_WRAPPER" ]]; then
    echo "Error: analyze-tasks.sh not found at $ANALYZE_WRAPPER" >&2
    exit 1
fi
chmod +x "$ANALYZE_WRAPPER"
echo "[speckit-analyze] ✓ analyze-tasks.sh wrapper installed"

# 3. Create speckit-analyze command entry point
ANALYZE_CMD="$SCRIPTS_DIR/speckit-analyze"
cat > "$ANALYZE_CMD" << 'EOF'
#!/usr/bin/env bash
# speckit-analyze command - Entry point for task analysis
# Part of speckit-analyze extension

set -euo pipefail

SCRIPT_DIR="$(CDPATH="" cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/common.sh"

eval $(get_feature_paths)

TASKS_FILE="${1:-$IMPL_TASKS}"
shift || true

# Default output directory
OUTPUT_DIR="${IMPL_TASKS%/*}/analysis"

# Pass all remaining args to Python
PYTHONPATH="${SPECIFY_DIR}/python:$PYTHONPATH" python3 -m speckit_analyzer.cli analyze "$TASKS_FILE" --output "$OUTPUT_DIR" "$@"
EOF

chmod +x "$ANALYZE_CMD"
echo "[speckit-analyze] ✓ speckit-analyze command created"

# 4. Update tasks-template.md with Score/Delegation section (if not already)
TEMPLATE_FILE="$TEMPLATES_DIR/tasks-template.md"
if ! grep -q "Score & Delegation" "$TEMPLATE_FILE" 2>/dev/null; then
    echo "[speckit-analyze] Updating tasks-template.md with Score/Delegation section..."
    cat >> "$TEMPLATE_FILE" << 'EOF'

---

## Score & Delegation (auto-generated by /speckit.analyze)

**Thresholds**: Complexity ≤ 5 | Context ≤ 100,000 tokens

| Task | Complexity | Est. LOC | Context Tokens | Delegable | Package |
|------|------------|----------|----------------|-----------|---------|
| T001 | 3 | 120 | 25,000 | ✅ | delegation_package/T001/ |
| T002 | 7 | 450 | 180,000 | ❌ (complexity) | - |

> Run `/speckit.analyze` to refresh scores after task modifications.
EOF
    echo "[speckit-analyze] ✓ tasks-template.md updated"
else
    echo "[speckit-analyze] ✓ tasks-template.md already has Score/Delegation section"
fi

# 5. Create analysis-template.md for reports
ANALYSIS_TEMPLATE="$TEMPLATES_DIR/analysis-template.md"
if [[ ! -f "$ANALYSIS_TEMPLATE" ]] || [[ "$FORCE" == "true" ]]; then
    cat > "$ANALYSIS_TEMPLATE" << 'EOF'
---
description: "Analysis report template for speckit-analyzer"
---

# Analysis Report: [FEATURE NAME]

**Generated**: [DATE]
**Tasks File**: [PATH]
**Thresholds**: Complexity ≤ [X] | Context ≤ [Y] tokens

## Summary

- **Total Tasks**: [N]
- **Delegable**: [N] ([P]%)
- **Non-Delegable (Complexity)**: [N]
- **Non-Delegable (Context)**: [N]
- **Non-Delegable (Both)**: [N]
- **Critical Path**: [X] days
- **Parallelizable**: [Y] days

## Delegable Tasks

| Task | Complexity | Est. LOC | Context Tokens | Package |
|------|------------|----------|----------------|---------|
| T### | # | #,### | #,### | delegation_package/T###/ |

## Critical Path

[Task IDs in critical path order]

## Parallelization Opportunities

| Phase | Tasks | Days Saved | Risk |
|-------|-------|------------|------|
| # | T###, T### | #.# | low/medium/high |

## Threshold Analysis

See `threshold_analysis.md` for detailed threshold sweep results.

## Next Steps

1. Review delegable tasks for delegation to small LLMs
2. Check `delegation_package/T###/context.md` for minimal context
3. Adjust thresholds if needed: `/speckit.analyze --threshold complexity=X,context=Y`
EOF
    echo "[speckit-analyze] ✓ analysis-template.md created"
else
    echo "[speckit-analyze] ✓ analysis-template.md already exists"
fi

# 6. Verify Python package is importable
echo "[speckit-analyze] Verifying Python package..."
if PYTHONPATH="$SPECIFY_DIR/python:${PYTHONPATH:-}" python3 -c "import speckit_analyzer; print('✓ Package importable')" 2>/dev/null; then
    echo "[speckit-analyze] ✓ Python package verified"
else
    echo "[speckit-analyze] ⚠ Python package not importable - installing in development mode..."
    cd "$SPECIFY_DIR/python/speckit_analyzer" && pip install -e . --break-system-packages -q
    echo "[speckit-analyze] ✓ Python package installed"
fi

# 7. Create/update common.sh if needed (ensure get_feature_paths exists)
COMMON_SH="$SCRIPTS_DIR/common.sh"
if ! grep -q "get_feature_paths" "$COMMON_SH" 2>/dev/null; then
    echo "[speckit-analyze] ⚠ common.sh may be missing get_feature_paths - check manually"
fi

echo ""
echo "[speckit-analyze] Integration complete!"
echo ""
echo "Next steps:"
echo "  1. Create a new feature: /speckit.specify 'your feature'"
echo "  2. Generate tasks: /speckit.tasks"
echo "  3. Analyze tasks: /speckit.analyze"
echo ""
echo "Or analyze existing tasks:"
echo "  /speckit.analyze specs/###-feature/tasks.md"
echo ""
echo "Available options:"
echo "  --calibrate        Calibrate from completed tasks"
echo "  --enrich           Enrich tasks.md with scores"
echo "  --threshold X,Y    Custom delegation thresholds"
echo "  --json             Output JSON to stdout"
echo "  --sweep            Full threshold sweep analysis"