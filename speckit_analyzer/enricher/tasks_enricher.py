"""Enrich tasks.md with scores and delegation info."""

import re
from pathlib import Path
from typing import Optional

from ..parser.models import Task, AnalysisResult


def enrich_tasks_file(
    tasks_file: Path,
    result: AnalysisResult,
    thresholds: dict,
    backup: bool = True
) -> str:
    """Enrich tasks.md file with scores."""
    content = tasks_file.read_text(encoding='utf-8')
    enriched = enrich_tasks_content(content, result, thresholds)

    if backup:
        backup_file = tasks_file.with_suffix('.md.bak')
        backup_file.write_text(content, encoding='utf-8')

    tasks_file.write_text(enriched, encoding='utf-8')
    return enriched


def enrich_tasks_content(content: str, result: AnalysisResult, thresholds: dict) -> str:
    """Enrich tasks.md content with scores."""
    task_map = {t.id: t for t in result.tasks}

    def replace_task_section(match):
        task_id = match.group(1)
        if task_id not in task_map:
            return match.group(0)

        task = task_map[task_id]
        if not task.score:
            return match.group(0)

        score_line = (
            f"**Score**: complexity={task.score.complexity}, "
            f"est_loc={task.score.est_loc}, "
            f"context_tokens={task.score.context_tokens}, "
            f"delegable={str(task.delegable).lower()}"
        )

        if task.context_package_path:
            score_line += f", **ContextPackage**: {task.context_package_path}"

        section = match.group(0)

        if "**Score**" not in section:
            lines = section.split('\n')
            insert_idx = 1
            for i, line in enumerate(lines):
                if line.startswith('**Phase**') or line.startswith('**Module**'):
                    insert_idx = i + 1
            lines.insert(insert_idx, score_line)
            return '\n'.join(lines)

        return section

    enriched = re.sub(
        r'(###\s+T\d+\s+.+?(?=\n###\s+T\d+|\n## |\Z))',
        replace_task_section,
        content,
        flags=re.DOTALL
    )

    delegation_table = generate_delegation_table(result, thresholds)
    enriched = inject_delegation_section(enriched, delegation_table)

    return enriched


def generate_delegation_table(result: AnalysisResult, thresholds: dict) -> str:
    """Generate delegation summary table."""
    lines = [
        "",
        "---",
        "",
        "## Score & Delegation (auto-generated by /speckit.analyze)",
        "",
        f"**Thresholds**: Complexity ≤ {thresholds.get('complexity', 5)} | Context ≤ {thresholds.get('context_tokens', 100000):,} tokens",
        "",
        "| Task | Complexity | Est. LOC | Context Tokens | Delegable | Package |",
        "|------|------------|----------|----------------|-----------|---------|",
    ]

    for task in sorted(result.tasks, key=lambda t: t.id):
        if not task.score:
            continue

        complexity = task.score.complexity
        loc = task.score.est_loc
        ctx = task.score.context_tokens
        delegable = "✅" if task.delegable else "❌"
        reason = ""
        if not task.delegable:
            reasons = []
            if task.score.complexity > thresholds.get('complexity', 5):
                reasons.append("complexity")
            if task.score.context_tokens > thresholds.get('context_tokens', 100000):
                reasons.append("context")
            reason = f" ({', '.join(reasons)})"
            delegable += reason

        package = task.context_package_path or "-"

        lines.append(f"| {task.id} | {complexity} | {loc:,} | {ctx:,} | {delegable} | {package} |")

    lines.extend([
        "",
        f"> Run `/speckit.analyze` to refresh scores after task modifications.",
        ""
    ])

    return '\n'.join(lines)


def inject_delegation_section(content: str, delegation_table: str) -> str:
    """Inject delegation table before Dependencies section or at end."""
    dep_section_pattern = r'(## Dependencies & Execution Order)'

    match = re.search(dep_section_pattern, content)
    if match:
        pos = match.start()
        return content[:pos] + delegation_table + '\n' + content[pos:]

    return content + '\n' + delegation_table